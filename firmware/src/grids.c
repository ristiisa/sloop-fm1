static const uint8_t GRIDS_MAP[5][5] = {          /* drum_map[x][y]: the node there */
    {10, 8, 0, 9, 11}, {15, 7, 13, 12, 6}, {18, 14, 4, 5, 3}, {23, 16, 21, 1, 2}, {24, 19, 17, 20, 22},
};
static const uint8_t GRIDS_LANE[3] = {LANE_KICK, LANE_SNARE, LANE_HAT};
static struct {
    uint8_t k[4];                        /* the knobs 0..127: X, Y, DENSITY, CHAOS (not saved) */
    uint8_t last;                        /* the knob of the touch going on (ui_studio.c grids_turn) */
    uint32_t seed, t, sess;              /* CHAOS's draws, the touch's last turn (ms) and its undo */
} grids = {{64, 64, 64, 0}, 0xFF, 1, 0, 0};
static const uint8_t *grids_n[4];        /* grids_make: the four nodes around X / Y */
static uint32_t grids_fx, grids_fy;

static uint32_t g8(uint32_t v) { return v * 2u + (v >> 6); }    /* a knob 0..127 -> 0..255 */
static uint32_t u8mix(uint32_t a, uint32_t b, uint32_t bal) { return (a * (255u - bal) + b * bal) >> 8; }
static void grids_at(uint32_t x, uint32_t y)      /* X / Y 0..255: the nodes around, how far between */
{
    uint32_t i = x >> 6, j = y >> 6;
    grids_n[0] = GRIDS_NODE[GRIDS_MAP[i][j]];
    grids_n[1] = GRIDS_NODE[GRIDS_MAP[i + 1u][j]];
    grids_n[2] = GRIDS_NODE[GRIDS_MAP[i][j + 1u]];
    grids_n[3] = GRIDS_NODE[GRIDS_MAP[i + 1u][j + 1u]];
    grids_fx = (x << 2) & 255u;
    grids_fy = (y << 2) & 255u;
}
static uint32_t grids_level(uint32_t step, uint32_t part)   /* ReadDrumMap: the level there (grids_at) */
{
    uint32_t o = part * 32u + step;
    return u8mix(u8mix(grids_n[0][o], grids_n[1][o], grids_fx), u8mix(grids_n[2][o], grids_n[3][o], grids_fx), grids_fy);
}
/* part p on step g (0..31) of a bar perturbed by pr: 0 no hit, else its level + 1 (over 192: the accent, HARD) */
static uint32_t grids_hit(uint32_t g, uint32_t p, uint32_t pr)
{
    uint32_t v = grids_level(g, p);
    v = v < 255u - pr ? v + pr : 255u;
    if (v <= 255u - g8(grids.k[2]))
        return 0;
    return 1u + (v > 192u ? LV_HARD : v > 128u ? LV_NORM : v > 64u ? LV_SOFT : LV_GHOST);
}
static void grids_make(track_t *t)               /* the map into the kick, snare and hat lanes within LEN */
{
    uint32_t len = trk_len(t), spb = t->p[P_SDIV] == 3 ? 32u : 16u, i, p, g, h;
    uint8_t pr[3] = {0, 0, 0};
    dstep_t s;
    grids_at(g8(grids.k[0]), g8(grids.k[1]));
    dice_rs = grids.seed | 1u;                    /* (drnd: dice.c) */
    for (i = 0; i < len; i++) {
        if (i % spb == 0u)                        /* a bar: each part's perturbation */
            for (p = 0; p < 3u; p++)
                pr[p] = (uint8_t)(drnd(256) * (g8(grids.k[3]) >> 2) >> 8);
        s = t->dstep[i];
        g = spb == 32u ? i % 32u : 2u * (i % 16u);
        for (p = 0; p < 3u; p++) {
            dstep_clr(&s, GRIDS_LANE[p]);
            if ((h = grids_hit(g, p, pr[p])) != 0)
                dstep_set(&s, GRIDS_LANE[p], h - 1u, spb == 16u && grids_hit(g + 1u, p, pr[p]));
        }
        if (memcmp(&s, &t->dstep[i], sizeof s)) {
            fm1_irq_off();
            t->dstep[i] = s;
            t->cond[i] = CN_ALWAYS;
            plk_clear_step(t, i);
            fm1_irq_on();
        }
    }
    t->seq_active = 1;
}
